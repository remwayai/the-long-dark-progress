/* The Long Dark — progress site renderer.
   Reads data/board.json (generated by tools/sync.mjs) and draws the dashboard.
   No dependencies, no build step: this file runs as-is on GitHub Pages. */

const SVG_NS = 'http://www.w3.org/2000/svg';

const CSS = getComputedStyle(document.documentElement);
const tok = (n) => CSS.getPropertyValue(n).trim();

const STATE = [
  { key: 'done',        label: 'Done',        color: tok('--state-done') },
  { key: 'in_progress', label: 'In progress', color: tok('--state-progress') },
  { key: 'todo',        label: 'Todo',        color: tok('--state-todo') },
];

// Categorical slots in fixed order — a stream keeps its hue however the board is filtered.
const STREAM_COLOR = {
  visual:   tok('--series-1'),
  gameplay: tok('--series-2'),
  pipeline: tok('--series-3'),
  infra:    tok('--series-4'),
};

const SURFACE = tok('--surface-1');
const GAP = 2;          // the surface gap between touching marks
const BAR = 22;         // bar thickness, capped under 24px
const CAP = 4;          // rounded data-end radius

const el = (id) => document.getElementById(id);
const tooltip = el('tooltip');

/* ------------------------------------------------------------------ utils */

function svg(tag, attrs = {}) {
  const node = document.createElementNS(SVG_NS, tag);
  for (const [k, v] of Object.entries(attrs)) node.setAttribute(k, v);
  return node;
}

function fmtDate(iso) {
  if (!iso) return '';
  return new Date(iso).toLocaleDateString('en-GB', { day: 'numeric', month: 'short', year: 'numeric' });
}

function fmtDateTime(iso) {
  if (!iso) return '';
  return new Date(iso).toLocaleString('en-GB', {
    day: 'numeric', month: 'short', year: 'numeric', hour: '2-digit', minute: '2-digit', timeZoneName: 'short',
  });
}

// Rounded on one side only: horizontal bars round their data-end, square at the baseline.
function barPath(x, y, w, h, r, roundRight) {
  const rr = roundRight ? Math.min(r, w) : 0;
  if (w <= 0) return '';
  return `M${x},${y} H${x + w - rr} ${rr ? `a${rr},${rr} 0 0 1 ${rr},${rr}` : ''} V${y + h - rr} ${rr ? `a${rr},${rr} 0 0 1 ${-rr},${rr}` : ''} H${x} Z`;
}

function showTip(evt, html) {
  tooltip.innerHTML = html;
  tooltip.dataset.show = '1';
  const pad = 14;
  const r = tooltip.getBoundingClientRect();
  let x = evt.clientX + pad;
  let y = evt.clientY + pad;
  if (x + r.width > window.innerWidth - 8) x = evt.clientX - r.width - pad;
  if (y + r.height > window.innerHeight - 8) y = evt.clientY - r.height - pad;
  tooltip.style.left = `${Math.max(8, x)}px`;
  tooltip.style.top = `${Math.max(8, y)}px`;
}

function hideTip() { tooltip.dataset.show = '0'; }

function attachTip(node, html) {
  node.addEventListener('mousemove', (e) => showTip(e, html));
  node.addEventListener('mouseleave', hideTip);
}

function legend(target, items) {
  target.innerHTML = '';
  for (const it of items) {
    const wrap = document.createElement('span');
    wrap.className = 'legend-item';
    const sw = document.createElement('span');
    sw.className = `legend-swatch${it.line ? ' line' : ''}`;
    sw.style.background = it.color;
    if (it.dashed) { sw.className = 'legend-swatch dash'; sw.style.background = 'transparent'; sw.style.color = it.color; }
    wrap.append(sw, document.createTextNode(it.label));
    target.append(wrap);
  }
}

function emptyState(target, message) {
  target.innerHTML = `<p class="empty">${message}</p>`;
}

/* ------------------------------------------------------- stacked bar rows */

function stackedRows(target, rows, { unit = 'tickets' } = {}) {
  target.innerHTML = '';
  if (!rows.length) { emptyState(target, 'Nothing on the board yet.'); return; }

  const W = 900, labelW = 132, valueW = 54, rowH = 44;
  const plotW = W - labelW - valueW;
  const H = rows.length * rowH + 8;
  const max = Math.max(1, ...rows.map((r) => r.total));

  const s = svg('svg', { viewBox: `0 0 ${W} ${H}`, role: 'img', 'aria-label': `Stacked bars, ${unit} by state` });

  rows.forEach((row, i) => {
    const y = i * rowH + 6;

    const label = svg('text', {
      x: 0, y: y + BAR / 2 + 5, fill: tok('--text-secondary'), 'font-size': 13,
    });
    label.textContent = row.label;
    s.append(label);

    // Track: the full scope of this row, so an empty row still reads as a row.
    const trackW = (row.total / max) * plotW;
    const track = svg('path', {
      d: barPath(labelW, y, trackW, BAR, CAP, true),
      fill: tok('--surface-2'),
    });
    s.append(track);

    let x = labelW;
    const segs = STATE.map((st) => ({ ...st, n: row[st.key] || 0 })).filter((sg) => sg.n > 0);
    segs.forEach((sg, j) => {
      const wRaw = (sg.n / max) * plotW;
      const last = j === segs.length - 1;
      const w = Math.max(1, last ? wRaw : wRaw - GAP); // 2px of surface separates touching segments
      const p = svg('path', {
        d: barPath(x, y, w, BAR, CAP, last),
        fill: sg.color,
      });
      attachTip(p, `<div class="t-title">${row.label}</div><div class="t-row">${sg.label}: ${sg.n} of ${row.total}</div>`);
      s.append(p);
      x += wRaw;
    });

    const val = svg('text', {
      x: W - valueW + 12, y: y + BAR / 2 + 5,
      fill: tok('--text-primary'), 'font-size': 13, 'font-variant-numeric': 'tabular-nums',
    });
    val.textContent = `${row.done}/${row.total}`;
    s.append(val);
  });

  target.append(s);
}

/* ------------------------------------------------------------- burn-up */

function burnup(target, series) {
  target.innerHTML = '';
  const closedEver = series.some((p) => p.closed > 0);
  if (series.length < 2 || !closedEver) {
    emptyState(target, 'The burn-up needs a second day of history before it can draw a line. The board was seeded today.');
    return;
  }

  const W = 900, H = 300, m = { t: 16, r: 56, b: 34, l: 40 };
  const plotW = W - m.l - m.r, plotH = H - m.t - m.b;
  const maxY = Math.max(...series.map((p) => p.total)) * 1.1;
  const t0 = new Date(series[0].date).getTime();
  const t1 = new Date(series[series.length - 1].date).getTime();
  const span = Math.max(1, t1 - t0);

  const X = (d) => m.l + ((new Date(d).getTime() - t0) / span) * plotW;
  const Y = (v) => m.t + plotH - (v / maxY) * plotH;

  const s = svg('svg', { viewBox: `0 0 ${W} ${H}`, role: 'img', 'aria-label': 'Burn-up: closed tickets against total scope' });

  // gridlines — hairline, solid, recessive
  const ticks = 4;
  for (let i = 0; i <= ticks; i++) {
    const v = (maxY / ticks) * i;
    const y = Y(v);
    s.append(svg('line', { x1: m.l, x2: W - m.r, y1: y, y2: y, stroke: tok('--grid'), 'stroke-width': 1 }));
    const lab = svg('text', { x: m.l - 10, y: y + 4, 'text-anchor': 'end', fill: tok('--text-muted'), 'font-size': 11, 'font-variant-numeric': 'tabular-nums' });
    lab.textContent = Math.round(v);
    s.append(lab);
  }
  s.append(svg('line', { x1: m.l, x2: W - m.r, y1: Y(0), y2: Y(0), stroke: tok('--axis'), 'stroke-width': 1 }));

  const line = (key, color, dashed) => {
    const d = series.map((p, i) => `${i ? 'L' : 'M'}${X(p.date)},${Y(p[key])}`).join(' ');
    s.append(svg('path', {
      d, fill: 'none', stroke: color, 'stroke-width': 2,
      'stroke-linejoin': 'round', 'stroke-linecap': 'round',
      ...(dashed ? { 'stroke-dasharray': '6 5' } : {}),
    }));
  };

  // area wash under the closed line
  const areaD = `${series.map((p, i) => `${i ? 'L' : 'M'}${X(p.date)},${Y(p.closed)}`).join(' ')} L${X(series[series.length - 1].date)},${Y(0)} L${X(series[0].date)},${Y(0)} Z`;
  s.append(svg('path', { d: areaD, fill: tok('--series-1'), opacity: 0.10 }));

  line('total', tok('--text-muted'), true);
  line('closed', tok('--series-1'), false);

  // x labels: first and last only, so they never collide
  [series[0], series[series.length - 1]].forEach((p, i) => {
    const t = svg('text', {
      x: X(p.date), y: H - 10, fill: tok('--text-muted'), 'font-size': 11,
      'text-anchor': i === 0 ? 'start' : 'end',
    });
    t.textContent = fmtDate(p.date);
    s.append(t);
  });

  // direct end-labels — the two series separate at the right edge
  const last = series[series.length - 1];
  const endLabel = (v, color, text) => {
    const t = svg('text', { x: X(last.date) + 10, y: Y(v) + 4, fill: color, 'font-size': 12, 'font-variant-numeric': 'tabular-nums' });
    t.textContent = text;
    s.append(t);
  };
  endLabel(last.total, tok('--text-muted'), `${last.total} scope`);
  endLabel(last.closed, tok('--text-secondary'), `${last.closed} done`);

  // end dot with a 2px surface ring
  s.append(svg('circle', { cx: X(last.date), cy: Y(last.closed), r: 4, fill: tok('--series-1'), stroke: SURFACE, 'stroke-width': 2 }));

  // crosshair + tooltip
  const cross = svg('line', { x1: 0, x2: 0, y1: m.t, y2: m.t + plotH, stroke: tok('--axis'), 'stroke-width': 1, opacity: 0 });
  s.append(cross);
  const hit = svg('rect', { x: m.l, y: m.t, width: plotW, height: plotH, fill: 'transparent' });
  hit.addEventListener('mousemove', (e) => {
    const box = s.getBoundingClientRect();
    const px = ((e.clientX - box.left) / box.width) * W;
    let best = series[0], bd = Infinity;
    for (const p of series) { const d = Math.abs(X(p.date) - px); if (d < bd) { bd = d; best = p; } }
    cross.setAttribute('x1', X(best.date));
    cross.setAttribute('x2', X(best.date));
    cross.setAttribute('opacity', 1);
    showTip(e, `<div class="t-title">${fmtDate(best.date)}</div><div class="t-row">Closed: ${best.closed}</div><div class="t-row">Scope: ${best.total}</div>`);
  });
  hit.addEventListener('mouseleave', () => { cross.setAttribute('opacity', 0); hideTip(); });
  s.append(hit);

  target.append(s);
}

/* --------------------------------------------------------------- table */

function renderTable(tickets, streams, filterKey) {
  const wrap = el('table');
  const rows = filterKey === 'all' ? tickets : tickets.filter((t) => t.stream === filterKey);
  if (!rows.length) { emptyState(wrap, 'No tickets in this stream.'); return; }

  const stateOf = (t) => STATE.find((s) => s.key === t.status) || STATE[2];
  const order = { in_progress: 0, todo: 1, done: 2 };
  rows.sort((a, b) => (order[a.status] - order[b.status]) || (a.number - b.number));

  const table = document.createElement('table');
  table.innerHTML = `
    <thead><tr>
      <th scope="col">#</th><th scope="col">Ticket</th><th scope="col">Stream</th>
      <th scope="col">State</th><th scope="col">Updated</th>
    </tr></thead>
    <tbody>${rows.map((t) => {
      const st = stateOf(t);
      const sn = streams.find((s) => s.key === t.stream);
      return `<tr>
        <td class="num">${t.number}</td>
        <td class="title">${t.title}</td>
        <td><span class="chip"><span class="legend-swatch" style="background:${STREAM_COLOR[t.stream] || tok('--text-muted')}"></span>${sn ? sn.label : t.stream}</span></td>
        <td><span class="chip"><span class="legend-swatch" style="background:${st.color}"></span>${st.label}</span></td>
        <td class="when">${fmtDate(t.closed || t.updated || t.created)}</td>
      </tr>`;
    }).join('')}</tbody>`;
  wrap.innerHTML = '';
  wrap.append(table);
}

function renderFilters(tickets, streams) {
  const box = el('filters');
  box.innerHTML = '';
  const mk = (key, label, color) => {
    const b = document.createElement('button');
    b.type = 'button';
    b.className = 'chip-btn';
    b.setAttribute('aria-pressed', key === 'all');
    b.innerHTML = color ? `<span class="legend-swatch" style="background:${color}"></span>${label}` : label;
    b.addEventListener('click', () => {
      [...box.children].forEach((c) => c.setAttribute('aria-pressed', 'false'));
      b.setAttribute('aria-pressed', 'true');
      renderTable(tickets, streams, key);
    });
    box.append(b);
  };
  mk('all', `All ${tickets.length}`, null);
  streams.forEach((s) => mk(s.key, `${s.label} ${s.total}`, STREAM_COLOR[s.key]));
}

/* --------------------------------------------------------------- inbox */

function renderInbox(items, streams) {
  const box = el('inbox-list');
  el('inbox-count').textContent = items ? items.length : 0;
  if (!items || !items.length) {
    emptyState(box, 'Nothing needs you right now. Both agents are unblocked.');
    el('inbox').dataset.quiet = '1';
    return;
  }
  el('inbox').dataset.quiet = '0';
  box.innerHTML = items.map((it) => {
    const sn = streams.find((s) => s.key === it.stream);
    return `<article class="ask">
      <span class="ask-rail" style="background:${STREAM_COLOR[it.stream] || tok('--text-muted')}"></span>
      <div class="ask-body">
        <h3>${it.title}</h3>
        <p class="ask-text">${it.ask}</p>
        <p class="ask-meta">ticket #${it.number} · ${sn ? sn.label : it.stream}${
          it.from ? ` · asked by ${it.from}` : ''} · ${fmtDate(it.at)}</p>
      </div>
    </article>`;
  }).join('');
}

/* -------------------------------------------------------------- devlog */

function renderDevlog(entries) {
  const box = el('devlog');
  if (!entries || !entries.length) {
    emptyState(box, 'No entries yet. The first one is written the day a ticket closes.');
    return;
  }
  box.innerHTML = entries.map((e) => `
    <article class="entry">
      <h3>${e.title}</h3>
      <p class="entry-meta">${fmtDate(e.date)} · ticket #${e.number}</p>
      ${e.note ? `<p class="note">${e.note}</p>` : ''}
    </article>`).join('');
}

/* ---------------------------------------------------------------- boot */

function render(data) {
  const c = data.counts;

  el('stamp').textContent = `${c.total} tickets on the board · last updated ${fmtDateTime(data.generated)}`;
  el('foot-stamp').textContent = `Generated ${fmtDateTime(data.generated)} from the team's ticket board.`;

  const pct = c.total ? Math.round((c.done / c.total) * 100) : 0;
  el('hero-pct').textContent = `${pct}%`;
  el('hero-fill').style.width = `${pct}%`;
  el('hero-meter').setAttribute('aria-label', `${c.done} of ${c.total} tickets complete`);
  el('hero-sub').textContent = `${c.done} of ${c.total} closed`;

  const tiles = [
    { label: 'In progress', value: c.in_progress, note: 'being worked right now', color: tok('--state-progress') },
    { label: 'Open', value: c.todo, note: 'queued and specified', color: tok('--state-todo') },
    { label: 'Waiting on you', value: c.inbox ?? c.human, note: 'play sessions and hardware', color: tok('--series-4') },
    { label: 'Free to try', value: c.free, note: 'no new hardware or spend', color: tok('--series-3') },
  ];
  el('tiles').innerHTML = tiles.map((t) => `
    <div class="tile">
      <span class="tile-label"><span class="tile-dot" style="background:${t.color}"></span>${t.label}</span>
      <span class="tile-value">${t.value}</span>
      <span class="tile-note">${t.note}</span>
    </div>`).join('');

  stackedRows(el('chart-stream'), data.streams);
  stackedRows(el('chart-owner'), data.owners);
  burnup(el('chart-burnup'), data.burnup);

  const stateLegend = STATE.map((s) => ({ label: s.label, color: s.color }));
  legend(el('legend-status'), stateLegend);
  legend(el('legend-status-2'), stateLegend);
  legend(el('legend-burnup'), [
    { label: 'Closed tickets', color: tok('--series-1'), line: true },
    { label: 'Total scope', color: tok('--text-muted'), line: true, dashed: true },
  ]);

  renderInbox(data.inbox, data.streams);
  renderFilters(data.tickets, data.streams);
  renderTable(data.tickets, data.streams, 'all');
  renderDevlog(data.devlog);
}

fetch(`data/board.json?v=${Date.now()}`)
  .then((r) => { if (!r.ok) throw new Error(`board.json ${r.status}`); return r.json(); })
  .then(render)
  .catch((err) => {
    el('main').insertAdjacentHTML('afterbegin',
      `<p class="empty">Could not load the board data (${err.message}).</p>`);
  });
